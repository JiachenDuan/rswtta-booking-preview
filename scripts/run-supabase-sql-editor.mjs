import fs from 'node:fs';
import crypto from 'node:crypto';
import { chromium } from 'playwright';

const [sqlPath, outputPath] = process.argv.slice(2);
if (!sqlPath || !outputPath) throw new Error('usage: node scripts/run-supabase-sql-editor.mjs SQL OUTPUT');
const sql = fs.readFileSync(sqlPath, 'utf8');
const sha256 = crypto.createHash('sha256').update(sql).digest('hex');
const browser = await chromium.connectOverCDP('http://127.0.0.1:18805');
const context = browser.contexts()[0];
let page = context.pages().find((p) => p.url().includes('/project/xtewfpzsyjeaqgkdttij/sql'));
if (!page) page = await context.newPage();
if (!page.url().includes('/project/xtewfpzsyjeaqgkdttij/sql')) await page.goto('https://supabase.com/dashboard/project/xtewfpzsyjeaqgkdttij/sql/new');
await page.waitForFunction(() => globalThis.monaco?.editor?.getEditors?.().length > 0, null, { timeout: 30000 });
const readbacks = await page.evaluate((value) => {
  const editors = globalThis.monaco.editor.getEditors();
  for (const editor of editors) editor.setValue(value);
  return editors.map((editor) => ({ value: editor.getValue(), visible: Boolean(editor.getDomNode()?.offsetParent) }));
}, sql);
const visibleReadbacks = readbacks.filter((item) => item.visible);
if (!visibleReadbacks.length || readbacks.some((item) => item.value !== sql)) throw new Error(`Monaco readback mismatch across ${readbacks.length} editors`);
const readbackSha256 = crypto.createHash('sha256').update(visibleReadbacks[0].value).digest('hex');
const runButtons = page.getByRole('button', { name: /^Run/ });
const runCount = await runButtons.count();
let run;
for (let i = 0; i < runCount; i++) if (await runButtons.nth(i).isVisible()) run = runButtons.nth(i);
if (!run) throw new Error('No visible Run button');
await page.waitForTimeout(750);
const responsePromise = page.waitForResponse((response) => response.request().method() === 'POST' && response.url().includes(`/platform/pg-meta/xtewfpzsyjeaqgkdttij/query?key=`), { timeout: 180000 });
await run.click();
const queryResponse = await responsePromise;
const requestBody = queryResponse.request().postData() ?? '';
const responseBody = await queryResponse.text();
await page.waitForTimeout(500);
const body = await page.locator('body').innerText();
const resultStart = Math.max(body.lastIndexOf('Results'), body.lastIndexOf('Failed to run sql query'));
const excerpt = body.slice(Math.max(0, resultStart), Math.min(body.length, resultStart + 20000));
const record = { sqlPath, sqlBytes: Buffer.byteLength(sql), sha256, readbackSha256, requestBodySha256: crypto.createHash('sha256').update(requestBody).digest('hex'), requestContainsExactSql: requestBody.includes(sql), requestBody, responseStatus: queryResponse.status(), responseBody, url: page.url(), capturedAt: new Date().toISOString(), excerpt };
fs.writeFileSync(outputPath, JSON.stringify(record, null, 2) + '\n');
console.log(JSON.stringify({ sqlPath, outputPath, sha256, readbackSha256, excerpt: excerpt.slice(0, 2000) }));
await browser.close();
